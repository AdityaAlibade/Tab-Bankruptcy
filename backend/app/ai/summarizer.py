import json
import re
from typing import List, Dict, Any

from app.config import OLLAMA_MODEL
from app.ai.ollama_service import query_ollama, OllamaServiceError

# Batch size: 10 tabs per AI request (ensures manageable prompt size and fast local inference)
BATCH_SIZE = 10

FALLBACK_SUMMARY = "No summary available for this tab."


def clean_summary_text(raw_summary: str) -> str:
    """
    Cleans raw summary generated by the model.
    - Removes markdown syntax
    - Removes emojis
    - Strips leading/trailing quotes and extra whitespace
    - Limits to a single sentence or falls back if empty
    """
    if not raw_summary:
        return FALLBACK_SUMMARY

    text = str(raw_summary).strip()

    # Strip markdown formatting like **bold** or *italic*
    text = re.sub(r"\*\*([^*]+)\*\*", r"\1", text)
    text = re.sub(r"\*([^*]+)\*", r"\1", text)
    text = re.sub(r"`([^`]+)`", r"\1", text)

    # Strip emojis and non-standard symbols using regex
    # Keep standard ASCII and common punctuation
    text = re.sub(r"[^\x00-\x7F]+", " ", text)

    # Remove quotes at ends
    text = text.strip("\"' \t\r\n")

    # Replace multiple whitespace/newlines with a single space
    text = re.sub(r"\s+", " ", text).strip()

    if not text:
        return FALLBACK_SUMMARY

    # If the summary is excessively long (over 250 chars), truncate cleanly at sentence or word
    if len(text) > 250:
        sentence_end = text[:250].rfind(".")
        if sentence_end > 50:
            text = text[:sentence_end + 1]
        else:
            space_end = text[:240].rfind(" ")
            text = text[:space_end] + "..." if space_end > 0 else text[:240] + "..."

    # Ensure it ends with a period if not ending with punctuation
    if text and text[-1] not in (".", "!", "?"):
        text += "."

    return text


def build_summary_batch_prompt(tabs_batch: List[Dict[str, Any]]) -> str:
    """
    Constructs a strict, structured batch prompt for Qwen to generate
    1 short, factual sentence (10–25 words) for each tab.
    """
    tab_lines = []
    for idx, tab in enumerate(tabs_batch):
        title = (tab.get("title") or "Untitled").strip()
        url = (tab.get("url") or "").strip()
        tab_lines.append(f"[{idx}] Title: {title} | URL: {url}")

    tabs_text = "\n".join(tab_lines)

    prompt = f"""You are an expert AI browser tab summarizer.
Generate a concise, factual 1-sentence summary (approximately 10 to 25 words) for each website based on its title and URL.

CRITICAL RULES:
1. Write EXACTLY ONE short, informative sentence per website.
2. Word count: strictly between 10 and 25 words per summary.
3. Be factual, objective, and useful.
4. Do NOT use markdown, emojis, bullet points, quotes, or preamble.
5. Return ONLY a valid JSON array of objects.
6. Each object must have "index" (matching the bracketed number) and "summary" (string).

Input Tabs:
{tabs_text}

JSON Output:"""

    return prompt


def parse_summary_batch_response(raw_text: str, expected_count: int) -> Dict[int, str]:
    """
    Parses the raw JSON response from Qwen.
    Strips code block wrappers, extracts the JSON array, cleans summaries,
    and fills missing items with FALLBACK_SUMMARY.
    """
    results: Dict[int, str] = {}
    cleaned = raw_text.strip()

    # Strip markdown code blocks if present
    if cleaned.startswith("```"):
        cleaned = re.sub(r"^```(?:json)?\s*", "", cleaned, flags=re.IGNORECASE)
        cleaned = re.sub(r"\s*```$", "", cleaned)
    cleaned = cleaned.strip()

    # Attempt to extract JSON array
    match = re.search(r"\[\s*\{.*\}\s*\]", cleaned, flags=re.DOTALL)
    json_str = match.group(0) if match else cleaned

    try:
        data = json.loads(json_str)
        if isinstance(data, list):
            for item in data:
                if isinstance(item, dict) and "index" in item:
                    try:
                        idx = int(item["index"])
                        raw_summary = str(item.get("summary", "")).strip()
                        cleaned_summary = clean_summary_text(raw_summary)
                        results[idx] = cleaned_summary
                    except (ValueError, TypeError):
                        continue
    except Exception as e:
        print(f"[Tab Bankruptcy AI] Warning: Failed to parse batch summary JSON response ({e}). Raw snippet:\n{raw_text[:300]}")

    # Ensure all expected indices have a summary
    for i in range(expected_count):
        if i not in results or not results[i]:
            results[i] = FALLBACK_SUMMARY

    return results


def summarize_tabs(tabs: List[Dict[str, Any]], model: str = OLLAMA_MODEL) -> List[Dict[str, Any]]:
    """
    Summarizes a list of tabs by batching them into groups of 10.
    Returns list of dicts with 'id', 'title', 'url', and 'summary'.
    """
    if not tabs:
        return []

    summarized_tabs: List[Dict[str, Any]] = []
    total_tabs = len(tabs)

    for start_idx in range(0, total_tabs, BATCH_SIZE):
        batch = tabs[start_idx : start_idx + BATCH_SIZE]
        prompt = build_summary_batch_prompt(batch)

        batch_num = start_idx // BATCH_SIZE + 1
        total_batches = (total_tabs + BATCH_SIZE - 1) // BATCH_SIZE

        print(
            f"[Tab Bankruptcy AI] Summarizing batch {batch_num}/{total_batches} "
            f"({len(batch)} tabs) using {model}..."
        )

        try:
            ai_result = query_ollama(prompt=prompt, model=model)
            raw_response = ai_result.get("response", "")
            batch_summaries = parse_summary_batch_response(raw_response, len(batch))
        except OllamaServiceError as e:
            print(f"[Tab Bankruptcy AI] Ollama error during batch summarization: {e.message}")
            raise e
        except Exception as e:
            print(f"[Tab Bankruptcy AI] Unexpected error during summarization batch: {e}")
            batch_summaries = {i: FALLBACK_SUMMARY for i in range(len(batch))}

        for idx, tab in enumerate(batch):
            assigned_summary = batch_summaries.get(idx, FALLBACK_SUMMARY)
            summarized_tabs.append({
                "id": tab.get("id"),
                "title": tab.get("title", "Untitled"),
                "url": tab.get("url", ""),
                "summary": assigned_summary,
            })

    return summarized_tabs
